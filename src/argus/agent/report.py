"""Suspicious Transaction Report (STR) drafting and grounding checks.

The STR body (subjects, trail, timeline, indicators, freeze list) is rendered from the case file.
An optional narrative (written by the LLM agent) is inserted only after `grounding_check`
confirms every number it quotes appears in the case facts.
"""

import json
import re

DISCLAIMER = ("DRAFT — generated by ARGUS for review by an authorised officer. "
              "Freeze actions are recommendations only and require officer approval.")


def red_flags(ind: dict) -> list:
    flags = []
    if ind["banks"] >= 3:
        flags.append(f"Funds crossed {ind['banks']} banks ({ind['cross_bank_share']:.0%} of transfers cross-bank).")
    if ind["median_pass_through_minutes"] is not None and ind["median_pass_through_minutes"] <= 120:
        flags.append(f"Rapid pass-through: mules forwarded funds after a median of "
                     f"{ind['median_pass_through_minutes']} minutes.")
    if ind["duration_minutes"] <= 24 * 60:
        flags.append(f"Entire movement completed within {ind['duration_minutes']} minutes.")
    if ind["dormant_accounts"]:
        flags.append(f"{ind['dormant_accounts']} account(s) were dormant before the ring activated.")
    if ind["shared_owner_groups"]:
        flags.append(f"{len(ind['shared_owner_groups'])} owner(s) control multiple ring accounts.")
    if ind["max_fan_out"] >= 3:
        flags.append(f"Fan-out: one account dispersed funds to {ind['max_fan_out']} accounts.")
    if ind["max_fan_in"] >= 3:
        flags.append(f"Fan-in: one account gathered funds from {ind['max_fan_in']} accounts.")
    if ind["has_cycle"]:
        flags.append("Circular flow: funds returned to an account already in the chain.")
    return flags


def render_str(case: dict, narrative: str | None = None) -> str:
    ind = case["indicators"]
    lines = [f"# Suspicious Transaction Report — {case['case_id']}", "", f"> {DISCLAIMER}", "",
             f"**Status:** {case['status']}  ", f"**Created:** {case['created_at']}  ",
             f"**Triggered by transfer:** #{case['seed_transfer']}", ""]
    if case.get("review"):
        r = case["review"]
        lines += [f"**Review:** {r['decision']} by {r['officer']} at {r['at']}" + (f" — {r['note']}" if r.get("note") else ""), ""]

    lines += ["## 1. Summary", ""]
    lines.append(narrative.strip() if narrative else
                 f"A ring of {ind['accounts']} accounts across {ind['banks']} banks moved "
                 f"{ind['amount_entered']:,.2f} from {', '.join(case['entry_accounts'])} through "
                 f"{ind['transfers']} transfers in {ind['duration_minutes']} minutes, ending at "
                 f"{len(case['exit_accounts'])} exit account(s).")
    lines += ["", "## 2. Grounds for suspicion", ""] + [f"- {f}" for f in red_flags(ind)]

    lines += ["", "## 3. Money trail", "", " → ".join(f"`{a}`" for a in case["money_trail"]), ""]

    lines += ["## 4. Subjects", "", "| Account | Bank | Role | Owner | Owner type | Prior transfers | Received | Sent | Score |",
              "|---|---|---|---|---|---|---|---|---|"]
    for p in case["accounts"]:
        lines.append(f"| `{p['account']}` | {p['bank']} | {p['role']} | {p['owner_entity']} | {p['owner_type']} | "
                     f"{p['transfers_before_ring']} | {p['received_in_ring']:,.2f} | {p['sent_in_ring']:,.2f} | "
                     f"{p['max_suspicion_score']:.2f} |")

    lines += ["", "## 5. Timeline", "", "| +min | From | To | Amount | Currency | Format | Score |",
              "|---|---|---|---|---|---|---|"]
    for e in case["timeline"]:
        lines.append(f"| {e['minute']} | `{e['from']}` | `{e['to']}` | {e['amount']:,.2f} | {e['currency']} | "
                     f"{e['format']} | {e['score']:.2f} |")

    lines += ["", "## 6. Recommended action (requires officer approval)", ""]
    if case["freeze_recommendation"]:
        lines += ["| Account | Bank | Role | Score | Reason |", "|---|---|---|---|---|"]
        lines += [f"| `{f['account']}` | {f['bank']} | {f['role']} | {f['score']:.2f} | {f['reason']} |"
                  for f in case["freeze_recommendation"]]
    else:
        lines.append("No account crossed the freeze threshold; continue monitoring.")
    return "\n".join(lines) + "\n"


_NUM = re.compile(r"(?<![\w.])(\d[\d,]*(?:\.\d+)?)(\s*%)?")


def _norm(n: str) -> float:
    return float(n.replace(",", ""))


_WORDS = {w: i for i, w in enumerate("zero one two three four five six seven eight nine ten eleven twelve thirteen "
                                       "fourteen fifteen sixteen seventeen eighteen nineteen twenty".split())}
_STOP = r"(?!(?:across|in|at|from|to|of|per|via|through|between|and|or|by|for|with|on)\b)"
_COUNT = re.compile(r"(?<![\d.,])\b(\d+|" + "|".join(_WORDS) + r")\s+(?:(additional|other|exit|destination|mule|ach)\s+)?"
                    r"(?:" + _STOP + r"[a-z\-]+\s+)?(dormant|banks?|accounts?|transfers?|transactions?)\b", re.I)


def count_claims_check(narrative: str, case: dict) -> list:
    """Counts stated in words or digits ('eight dormant accounts', '6 banks') must equal the case
    indicator they describe. Qualified counts ('four exit accounts', '5 additional accounts',
    '8 ACH transfers') may match the corresponding sub-count instead."""
    ind = case["indicators"]
    n_exit, n_entry = len(case["exit_accounts"]), len(case["entry_accounts"])
    allowed = {
        "dormant": {ind["dormant_accounts"]},
        "bank": {ind["banks"]},
        "account": {ind["accounts"], n_exit, n_entry, ind["accounts"] - n_entry, ind["accounts"] - n_entry - n_exit,
                    ind["dormant_accounts"], ind["max_fan_out"], ind["max_fan_in"]},
        "transfer": {ind["transfers"], *ind["payment_formats"].values(), ind["max_fan_out"], ind["max_fan_in"]},
    }
    bad = []
    for m in _COUNT.finditer(narrative):
        raw, qual, noun = m.group(1).lower(), (m.group(2) or "").lower(), m.group(3).lower()
        n = _WORDS[raw] if raw in _WORDS else int(raw)
        key = ("dormant" if noun == "dormant" else "bank" if noun.startswith("bank")
               else "account" if noun.startswith("account") else "transfer")
        if key == "account" and "dormant" in m.group(0).lower():
            key = "dormant"
        if n not in allowed[key]:
            bad.append(m.group(0))
    return bad


def grounding_check(narrative: str, case: dict, tol: float = 0.01) -> list:
    """Numbers in the narrative that do not match any number in the case facts (hallucination check).

    Every decimal and every number above 12 must match a case fact (0.5% relative tolerance, so
    rounding is fine); "89%" matches a fact of 0.889. Whole numbers up to 12 are allowed without a
    match (list numbering, dates); counts like "6 banks" are still checked when they exceed 12.
    """
    facts = {_norm(m.group(1)) for m in _NUM.finditer(json.dumps(case, default=str))}
    facts |= {round(f, 0) for f in facts} | {round(f, 1) for f in facts} | {round(f, 2) for f in facts}

    def known(v):
        return any(abs(v - f) <= tol or (f and abs(v - f) / abs(f) < 0.005) for f in facts)

    bad = count_claims_check(narrative, case)
    for m in _NUM.finditer(narrative):
        text, pct = m.group(1), m.group(2)
        v = _norm(text)
        if pct:
            if not (known(v / 100) or known(v)):
                bad.append(text + "%")
            continue
        if "." not in text and v <= 12:
            continue
        if not known(v):
            bad.append(text)
    return bad
